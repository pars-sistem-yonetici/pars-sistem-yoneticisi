export function translate(text: string, lang: Language, dictionary?: Record<string, string>): string {
  if (lang === 'tr') return text;
  return dictionary?.[text] ?? EN[text] ?? text;
}

export function translateFormat(
  text: string,
  lang: Language,
  vars: Record<string, string | number>,
  dictionary?: Record<string, string>,
): string {
  const template = translate(text, lang, dictionary);
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ''));
}
