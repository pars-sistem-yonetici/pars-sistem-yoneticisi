export function categoryIcon(category: string): string {
  if (category === 'Tümü') return '☑️';
  if (category.includes('Güvenlik')) return '🛡️';
  if (category.includes('Tarayıcı')) return '🌐';
  if (category.includes('İletişim')) return '💬';
  if (category.includes('Oyun')) return '🎮';
  if (category.includes('Geliştirme')) return '💻';
  if (category.includes('Medya')) return '🎬';
  if (category.includes('Paket')) return '📦';
  if (category.includes('Sistem')) return '⚙️';
  if (category.includes('Verimlilik')) return '📝';
  return '🧱';
}

/** Etikete karşılık gelen simge; bilinmeyen etiketlerde boş döner. */
export function iconFor(label: string): string {
  return ICONS[label] ?? '';
}

/** Buton ve başlıklarda kullanılan, giriş animasyonlu ikon sarmalayıcısı. */
export function UiIcon({ label, icon, className = '' }: {
  label?: string;
  icon?: string;
  className?: string;
}) {
  const value = icon || (label ? iconFor(label) : '');
  if (!value) return null;
  return <span className={`ui-icon ${className}`.trim()} aria-hidden="true">{value}</span>;
}
