export function categoryIcon(category: string): string {
  if (category === 'Tümü') return 'SquareCheck';
  const key = Object.keys(CATEGORY_GLYPHS).find((name) => category.includes(name));
  return key ? CATEGORY_GLYPHS[key] : 'Boxes';
}

/** Etikete karşılık gelen ikon adı; bilinmeyen etiketlerde boş döner. */
export function iconFor(label: string): string {
  return ICONS[label] ?? '';
}

/** Lucide ikonunu tek noktadan render eder; bilinmeyen adlarda yardım ikonu gösterir. */
export function Glyph({ name, size = 16, strokeWidth = 1.8, className = '' }: {
  name?: string;
  size?: number;
  strokeWidth?: number;
  className?: string;
}) {
  const resolved = name && GLYPHS[name] ? name : (name && LEGACY_GLYPHS[name]) || 'CircleHelp';
  const Icon = GLYPHS[resolved];
  return <Icon
    size={size}
    strokeWidth={strokeWidth}
    className={className || undefined}
    aria-hidden="true"
    focusable="false"
  />;
}

/** Buton ve başlıklarda kullanılan, giriş animasyonlu ikon sarmalayıcısı. */
export function UiIcon({ label, icon, className = '', size }: {
  label?: string;
  icon?: string;
  className?: string;
  size?: number;
}) {
  const value = icon || (label ? iconFor(label) : '');
  if (!value) return null;
  return (
    <span className={`ui-icon ${className}`.trim()} aria-hidden="true">
      <Glyph name={value} size={size} />
    </span>
  );
}
